#requires -PSEdition Core
#requires -Version 7.6.5

<#
.SYNOPSIS
    The winget manifest of an Xmip MSI, generated from the MSI itself and
    never kept by hand (ADR-0015 clause 2, amendment 2026-10-13).

.DESCRIPTION
    winget is the channel and the MSI the artifact behind it. A manifest is
    three files in winget's multi-file form, schema 1.28.0, the current one
    in microsoft/winget-cli on 2026-10-13: the version, the installer — the
    MSI's SHA-256 and its ProductCode, read from the MSI — and the default
    locale. The package identifier and the download address are the
    drafting's, the owner's to strike: nothing is published yet, so the
    address names where a GitHub release of the version would hold it.

    Style: doc/governance/powershell-style.md
#>


function New-XmipWingetManifest {
    <#
        .SYNOPSIS
            Writes the manifest of the MSI at Msi under
            Destination/<version>, and returns that folder.
    #>
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory = $true)]
        [string] $Msi,

        [Parameter(Mandatory = $true)]
        [string] $Version,

        [Parameter(Mandatory = $true)]
        [ValidateSet('x64', 'arm64')]
        [string] $Architecture,

        [Parameter(Mandatory = $true)]
        [string] $Destination
    )

    [string] $identifier = 'Xmip.Xmip'
    [string] $schema = '1.28.0'
    [string] $folder = Join-Path $Destination $Version
    $null = New-Item -ItemType Directory -Path $folder -Force

    [string] $sha = (Get-FileHash -LiteralPath $Msi -Algorithm SHA256).Hash
    [string] $productCode = Get-XmipMsiProperty -Msi $Msi -Name 'ProductCode'
    [string] $file = Split-Path -Path $Msi -Leaf
    [string] $url = "https://github.com/IlleNilsson/Xmip/releases/download/v$Version/$file"
    [string] $head = "# Generated by Build-XmipService -Package msi; not kept by hand.`n" +
        "PackageIdentifier: $identifier`nPackageVersion: $Version`n"
    [string] $tail = "ManifestVersion: $schema`n"

    $files = [ordered] @{
        "$identifier.yaml"                  = "$head" +
            "DefaultLocale: en-US`nManifestType: version`n$tail"
        "$identifier.installer.yaml"        = "$head" +
            "InstallerType: wix`nScope: machine`nInstallers:`n" +
            "  - Architecture: $Architecture`n" +
            "    InstallerUrl: $url`n" +
            "    InstallerSha256: $sha`n" +
            "    ProductCode: '$productCode'`n" +
            "ManifestType: installer`n$tail"
        "$identifier.locale.en-US.yaml"     = "$head" +
            "PackageLocale: en-US`nPublisher: Xmip`nPackageName: Xmip`n" +
            "License: AGPL-3.0-or-later`n" +
            "PackageUrl: https://github.com/IlleNilsson/Xmip`n" +
            "ShortDescription: The cross-platform Messaging & Integration Platform, " +
            "one node as a Windows service.`n" +
            "ManifestType: defaultLocale`n$tail"
    }

    $files.GetEnumerator() | ForEach-Object {
        [string] $path = Join-Path $folder $_.Key
        Set-Content -LiteralPath $path -Value $_.Value -NoNewline -Encoding utf8NoBOM
    }

    return $folder
}


function Get-XmipMsiProperty {
    <#
        .SYNOPSIS
            One value of an MSI's Property table, read through Windows
            Installer's own automation interface.
    #>
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory = $true)]
        [string] $Msi,

        [Parameter(Mandatory = $true)]
        [string] $Name
    )

    $installer = New-Object -ComObject WindowsInstaller.Installer
    # 0: read only.
    $database = $installer.OpenDatabase($Msi, 0)
    $view = $database.OpenView("SELECT ``Value`` FROM ``Property`` WHERE ``Property`` = '$Name'")
    $view.Execute()
    $record = $view.Fetch()

    try {
        if ($null -eq $record) {
            throw "FAILED: $Msi has no property $Name."
        }

        return [string] $record.StringData(1)
    }
    finally {
        $view.Close()
        $null = [Runtime.InteropServices.Marshal]::FinalReleaseComObject($database)
    }
}
